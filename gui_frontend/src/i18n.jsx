const LanguageContext = createContext(null);

// Solo en desarrollo: los avisos de claves ausentes no deben ensuciar la
// consola de producción (import.meta.env lo define Vite en dev/build/test).
const isDev = Boolean(import.meta.env && import.meta.env.DEV);

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try {
      return localStorage.getItem('gui_lang') || 'es';
    } catch {
      return 'es';
    }
  });

  useEffect(() => {
    try {
      localStorage.setItem('gui_lang', lang);
    } catch {
      // sin localStorage (modo privado): se ignora
    }
    // <html lang> sincronizado con el idioma de la GUI (lectores de pantalla,
    // traductores y correctores dependen del atributo, no del contexto React)
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo(() => {
    const t = (key, vars = {}) => {
      let s = STRINGS[lang]?.[key];
      if (s === undefined) {
        // Clave ausente (o typo): antes se devolvia la clave en silencio y el
        // usuario veia "sugDayX" en la UI sin ninguna pista. Aviso en
        // desarrollo + fallback a ES / a la propia clave.
        if (isDev) {
          const fallback = STRINGS.es[key] !== undefined ? 'usando fallback ES' : 'sin traducción: se muestra la clave';
          console.warn(`[i18n] Falta la clave "${key}" para el idioma "${lang}" (${fallback})`);
        }
        s = STRINGS.es[key] ?? key;
      }
      for (const [k, v] of Object.entries(vars)) {
        s = s.replaceAll(`{${k}}`, String(v));
      }
      return s;
    };
    return { lang, setLang, t };
  }, [lang]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(LanguageContext);
  if (ctx === null) {
    // Fallo explicito y comprensible: antes devolvia null y el crash llegaba
    // despues en `const { t } = useI18n()` como un "Cannot destructure
    // property 't' of null" sin ninguna pista de la causa real.
    throw new Error(
      'useI18n() debe usarse dentro de un <LanguageProvider>. Envuelve la app con <LanguageProvider> (ver src/main.jsx).'
    );
  }
  return ctx;
}
